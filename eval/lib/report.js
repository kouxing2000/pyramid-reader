// What the eval writes for people: the run's summary.md, and the rows of the settings'
// tested-models table (src/lib/tested-models.js, SPEC §5.4). Neither holds page text.

// Rounded down to a tenth, like the settings table: 94.95% must not read as a passing 95.0%.
const pct = (x) => (x === null ? '-' : `${(Math.floor(x * 1000 + 1e-9) / 10).toFixed(1)}%`);
const num = (x) => (x === null || x === undefined ? '-' : String(x));
const usd = (x) => `$${x.toFixed(x < 0.1 ? 4 : 2)}`;

/**
 * @param {{run: string, pages: object[], models: object[], skipped: string[], spend: number,
 *   common: object | null, nodes: object[]}} results  as eval.mjs score writes results.json
 * @returns {string} markdown
 */
export function summaryMarkdown(results) {
  const { run, pages, models, skipped, spend } = results;
  const kinds = Object.entries(pages.reduce((t, p) => ({ ...t, [p.kind]: (t[p.kind] ?? 0) + 1 }), {}))
    .map(([k, n]) => `${n} ${k}`).join(', ');
  const sites = new Set(pages.map((p) => new URL(p.url).hostname.replace(/^www\./, ''))).size;
  const lines = [
    `# Eval run ${run}`,
    '',
    `Generated by \`node eval/eval.mjs score --run ${run}\` from the raw trees in this run's local/ directory (not committed: they hold the pages' words).`,
    '',
    `- Pages: ${pages.length} (${kinds}) from ${sites} sites, listed in results.json by URL and text hash.`,
    `- Spend: ${usd(spend)} in spend.jsonl, claude -p's reported cost included.`,
    ...skipped.map((s) => `- ${s}`),
    '',
    '## Per model',
    '',
    '| Model | Trees | First-try valid | Quotes anchored | Basis anchored | Number flags | Verdict s (median / p90) | Tree s (median / p90) | Tokens in / out per tree | Cost per tree |',
    '|---|---|---|---|---|---|---|---|---|---|',
  ];
  for (const m of models) {
    lines.push(`| ${m.model}${m.via ? ` (${m.resolvedModel ?? '?'}, via ${m.via})` : ''} | ${m.built}/${m.attempted} | ${pct(m.firstTryRate)} | ` +
      `${pct(m.anchored)} (${m.evidence.unanchored} of ${m.evidence.total - m.evidence.derived} missing, ${m.evidence.repaired} repaired) | ` +
      `${pct(m.basisAnchored)} | ${m.numberFlaggedNodes}/${m.basis.total} nodes | ${num(m.seconds.verdict)} / ${num(m.seconds.verdictP90)} | ` +
      `${num(m.seconds.total)} / ${num(m.seconds.totalP90)} | ${m.tokens.perTreeInput} / ${m.tokens.perTreeOutput} | ` +
      `${usd(m.costPerTreeUsd)}${m.costEstimated ? ' (part estimated)' : ''} |`);
  }
  const all = models.reduce((t, m) => ({
    total: t.total + m.evidence.total - m.evidence.derived,
    found: t.found + m.evidence.anchored + m.evidence.repaired,
  }), { total: 0, found: 0 });
  lines.push('', `All models: ${pct(all.total ? all.found / all.total : null)} of ${all.total} evidence quotes resolve to an anchor (SPEC §9.4: at least 95%).`, '');
  lines.push('Columns: quotes anchored counts evidence found on the page, in the cited paragraph or, repaired, in another; derived values are left out. ' +
    'Basis anchored counts the basis sentence of the verdict and of each claim found the same way. ' +
    'Number flags counts the verdict and claims whose own words state a number none of their cited paragraphs holds. ' +
    'Times run from the request to the verdict drawn and to the whole tree, retries included.', '');
  const kindRows = Object.entries(models.reduce((t, m) => {
    for (const [kind, k] of Object.entries(m.byKind)) {
      const s = (t[kind] ??= { built: 0, evidence: 0, evidenceAnchored: 0 });
      for (const f of Object.keys(s)) s[f] += k[f];
    }
    return t;
  }, {}));
  lines.push('## By page kind, all models', '', '| Kind | Trees | Quotes anchored |', '|---|---|---|',
    ...kindRows.map(([kind, k]) => `| ${kind} | ${k.built} | ${pct(k.evidence ? k.evidenceAnchored / k.evidence : null)} |`), '');
  if (results.common && results.common.pages < pages.length) {
    lines.push(`## On the ${results.common.pages} pages every model built`, '',
      '| Model | Trees | Quotes anchored | Verdict s (median) | Tree s (median) | Cost per tree |',
      '|---|---|---|---|---|---|');
    for (const m of results.common.models) {
      lines.push(`| ${m.model} | ${m.built}/${m.attempted} | ${pct(m.anchored)} | ` +
        `${num(m.seconds.verdict)} | ${num(m.seconds.total)} | ${usd(m.costPerTreeUsd)} |`);
    }
    lines.push('');
  }
  const failures = models.flatMap((m) => m.failures.map((f) => `- ${m.model} ${f.page}: ${f.error}`));
  if (failures.length) lines.push('## Builds that produced no tree', '', ...failures, '');
  return lines.join('\n');
}

/**
 * The tested-models rows: one per model with a tree built, each by the model name its provider
 * reported (claude -p resolves an alias to its Anthropic API name). A row measured outside the
 * extension's own transport carries `via` and comes after the others.
 */
export function testedRows(results) {
  return results.models
    .filter((m) => m.built)
    .map((m) => ({
      provider: m.provider, model: m.resolvedModel ?? m.model, ...(m.via && { via: m.via }),
      anchored: m.anchored,
      verdictSeconds: m.seconds.verdict, totalSeconds: m.seconds.total,
      pages: m.built, measured: results.run,
    }))
    .sort((a, b) => Number(Boolean(a.via)) - Number(Boolean(b.via)));
}
